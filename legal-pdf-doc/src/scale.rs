//! Each line's own features on their scales (`machine::lines::LINE_FEATURES` and the word and look bits after them,
//! `WIDTH` in all) and the document's shape (`SHAPE`): each one's centre and spread, so what DOC reads is
//! `(value - centre) / spread` within ±8, held as one signed byte (`quantized`): a step of 8/127 of a spread. The dump
//! the fit trains on and the reader give DOC the same bytes. A feature's scale is part of its definition, fixed here:
//! the values are the train statistics of the fit that first read these features (export 12, epoch 3), so no fit
//! measures them again and no gold added changes how a document reads. A feature added or changed is given its scale here.

use crate::model::machine::lines::SHAPE;
use crate::model::machine::lines::WIDTH;

/// A value on its scale as DOC reads it: within ±8 of its centre's spreads, in steps of 8/127.
fn byte(value: f32, centre: f32, spread: f32) -> i8 {
    // Rounded to the nearest, ties to even, by the float's own rounding (1.5 × 2^23 added and taken off, exact for
    // |x| < 2^22): `round_ties_even` is a call into the C runtime on x86-64 without SSE4.1, once a feature of every line.
    const SHIFT: f32 = 12_582_912.0;
    let scaled = ((value - centre) / spread).clamp(-8.0, 8.0) * (127.0 / 8.0);
    ((scaled + SHIFT) - SHIFT) as i8
}

/// Each line's own features (`WIDTH` a line) as DOC reads them.
pub fn quantized(own: &[f32]) -> Vec<i8> {
    own.iter()
        .enumerate()
        .map(|(at, &v)| byte(v, CENTRE[at % WIDTH], SPREAD[at % WIDTH]))
        .collect()
}

/// The document's shape as DOC reads it.
pub fn shape(shape: &[f32; SHAPE]) -> [i8; SHAPE] {
    std::array::from_fn(|at| byte(shape[at], SHAPE_CENTRE[at], SHAPE_SPREAD[at]))
}

